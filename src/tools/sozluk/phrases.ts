export type Lang = 'en' | 'ar' | 'fa' | 'ku' | 'ru' | 'uk' | 'de';
export type Cat = 'tibbi' | 'kurtarma' | 'ihtiyaclar' | 'yon' | 'aile';

export interface Tr {
  /** yerel yazı */
  t: string;
  /** Türkçe harflerle okunuş (ar, fa, ru, uk için zorunlu) */
  p?: string;
  /** false → kaynakla doğrulanamadı */
  verified?: false;
}

export interface Phrase {
  id: string;
  cat: Cat;
  tr: string;
  /** dil → çeviri; null = bilerek boş bırakıldı (açık boşluk) */
  l: Record<Lang, Tr | null>;
}

