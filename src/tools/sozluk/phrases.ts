/** Türkçe duyarlı küçük harf + aksan sadeleştirme (arama için). */
export function fold(s: string): string {
  return s
    .toLocaleLowerCase('tr')
    .replace(/[âà]/g, 'a')
    .replace(/[îì]/g, 'i')
    .replace(/[ûù]/g, 'u')
    .replace(/ê/g, 'e')
    .replace(/[’'`ʿʾ]/g, '')
    .normalize('NFKC');
}

/** Türkçe, çeviri ve okunuş içinde arar; boş sorgu → tümü. */
export function searchPhrases(q: string, cat: Cat | 'all' = 'all', list: Phrase[] = PHRASES): Phrase[] {
  const f = fold(q.trim());
  return list.filter((p) => {
    if (cat !== 'all' && p.cat !== cat) return false;
    if (!f) return true;
    if (fold(p.tr).includes(f)) return true;
    return Object.values(p.l).some((x) => x && (fold(x.t).includes(f) || (x.p ? fold(x.p).includes(f) : false)));
  });
}

export function isVerified(p: Phrase): boolean {
  return Object.values(p.l).every((x) => x === null || x.verified !== false);
}
